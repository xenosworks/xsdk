#!/usr/bin/env python3
"""tests/probe_skin.c's container: xsdk_test's hlsl/grid_skin_vs.hlsl as tools/gen_xsc_shaders.py compiles it, by the
PC's build of xost with tests/probe_skin.patch, the library the first argument names. Writes a C header to the second.
Runs in WSL."""

import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "xenos-toolchain"))

import xsc.native as native  # noqa: E402

SPIRV = ROOT / "xenos-toolchain" / "xsc" / "testdata" / "hlsl" / "grid_skin_vs.hlsl.spv"
# xsdk's split (xsdk:src/gpu_setup.c).
REGISTERS = 64


def main():
    native.LIBRARY = Path(sys.argv[1])
    container, manifest, _ = native.compile_spirv(SPIRV.read_bytes(), REGISTERS, REGISTERS, optimize=True)
    if any(not isinstance(need[0], int) for need in manifest):
        raise SystemExit(f"grid_skin_vs.hlsl needs more than literals: {manifest}")
    words = struct.unpack(f">{len(container) // 4}I", container)
    lines = ["#ifndef PROBE_SKIN_SHADERS_H", "#define PROBE_SKIN_SHADERS_H", "", "#include <stdint.h>", "",
             '#include "xsdk/xsc.h"', "", "// Generated by tools/gen_skin_probe.py.", "",
             "static const uint32_t probe_skin_lanex[] = {"]
    lines += [f"\t0x{word:08X}," for word in words]
    lines += ["};", "", "static const XsdkXscNeed probe_skin_lanex_needs[] = {"]
    for reg, values in manifest:
        value = ", ".join(map(repr, values))
        lines.append(f"\t{{ .kind = XSDK_XSC_LITERAL, .reg = {reg}, .regs = 1, .value = {{ {value} }} }},")
    lines += ["};", "", "#endif"]
    Path(sys.argv[2]).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
