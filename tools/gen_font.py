#!/usr/bin/env python3
"""Generate the text calls' font: assets/fonts/10x20.bdf's glyphs in the blocks below as bits, for src/text.c.

The BDF is X11's misc-fixed 10x20, Markus Kuhn's ISO 10646 set, as X.Org's font-misc-misc 1.1.3 release ships it
(https://www.x.org/releases/individual/font/font-misc-misc-1.1.3.tar.xz). It's in the public domain: its COPYRIGHT
property and the release's COPYING read "Public domain font.  Share and enjoy."

The header holds each glyph's code point, ascending, and its 20 rows of 10 bits; glyph 0 is the font's default, the box
its DEFAULT_CHAR names, which is code point 0.

    gen_font.py --output src/text_font.h assets/fonts/10x20.bdf
"""

import argparse
import sys
from pathlib import Path

CELL_WIDTH = 10
CELL_HEIGHT = 20
# The atlas's cells: 102 across and 12 down a 1024x256 texture (src/text.c).
ATLAS_CELLS = (1024 // CELL_WIDTH) * (256 // CELL_HEIGHT)
# ASCII, Latin-1, Latin Extended-A, Greek, Cyrillic, general punctuation, currency, arrows, box drawing, block
# elements and geometric shapes: as many of each as the font has (docs/scope/57-text-and-ui.md, "The font").
BLOCKS = [(0x20, 0x7E), (0xA0, 0xFF), (0x100, 0x17F), (0x370, 0x3FF), (0x400, 0x4FF), (0x2000, 0x206F),
          (0x20A0, 0x20CF), (0x2190, 0x21FF), (0x2500, 0x257F), (0x2580, 0x259F), (0x25A0, 0x25FF)]
SOURCE = "https://www.x.org/releases/individual/font/font-misc-misc-1.1.3.tar.xz"
SOURCE_SHA256 = "79abe361f58bb21ade9f565898e486300ce1cc621d5285bec26e14b6a8618fed"


def fail(path, message):
    sys.exit(f"{path}: {message}")


def read_bdf(path):
    """The font's properties, and each glyph's encoding with its DWIDTH, BBX and bitmap rows as integers."""
    lines = path.read_text(encoding="ascii").splitlines()
    properties = {}
    glyphs = {}
    i = 0
    while i < len(lines):
        words = lines[i].split()
        i += 1
        if not words:
            continue
        if words[0] in ("FONTBOUNDINGBOX", "DEFAULT_CHAR", "FONT_ASCENT", "COPYRIGHT"):
            properties[words[0]] = lines[i - 1].split(None, 1)[1]
        if words[0] != "STARTCHAR":
            continue
        glyph = {}
        while lines[i] != "BITMAP":
            key, _, value = lines[i].partition(" ")
            glyph[key] = [int(word) for word in value.split()]
            i += 1
        i += 1
        width, height = glyph["BBX"][:2]
        bytes_per_row = (width + 7) // 8
        rows = [int(row, 16) for row in lines[i:i + height]]
        if lines[i + height] != "ENDCHAR" or any(len(row) != 2 * bytes_per_row for row in lines[i:i + height]):
            fail(path, f"glyph {glyph['ENCODING']}: a bitmap that isn't {height} rows of {bytes_per_row} bytes")
        i += height + 1
        glyph["rows"] = [row << (16 - 8 * bytes_per_row) for row in rows]
        glyphs[glyph["ENCODING"][0]] = glyph
    return properties, glyphs


def cell_rows(path, code_point, glyph, ascent):
    """The glyph's 20 rows in its cell, top first, the leftmost pixel in bit 15."""
    if glyph["DWIDTH"] != [CELL_WIDTH, 0]:
        fail(path, f"U+{code_point:04X} isn't {CELL_WIDTH} pixels wide")
    width, height, x, y = glyph["BBX"]
    top = ascent - (y + height)
    if x < 0 or x + width > CELL_WIDTH or top < 0 or top + height > CELL_HEIGHT:
        fail(path, f"U+{code_point:04X} reaches outside its {CELL_WIDTH}x{CELL_HEIGHT} cell")
    rows = [0] * CELL_HEIGHT
    for r, bits in enumerate(glyph["rows"]):
        rows[top + r] = bits >> x
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--output", type=Path, required=True, help="the header to write")
    parser.add_argument("bdf", type=Path, help="assets/fonts/10x20.bdf")
    args = parser.parse_args()
    properties, glyphs = read_bdf(args.bdf)
    if properties.get("FONTBOUNDINGBOX", "").split()[:2] != [str(CELL_WIDTH), str(CELL_HEIGHT)]:
        fail(args.bdf, f"not a {CELL_WIDTH}x{CELL_HEIGHT} font")
    default = int(properties["DEFAULT_CHAR"])
    ascent = int(properties["FONT_ASCENT"])
    chosen = [default] + sorted(c for c in glyphs if any(first <= c <= last for first, last in BLOCKS))
    if default != 0 or len(chosen) > ATLAS_CELLS:
        fail(args.bdf, f"the default glyph isn't code point 0, or {len(chosen)} glyphs don't fit {ATLAS_CELLS} cells")
    lines = [
        "// Generated by tools/gen_font.py from assets/fonts/10x20.bdf; don't edit.",
        "// X11's misc-fixed 10x20, Markus Kuhn's ISO 10646 set, from X.Org's font-misc-misc 1.1.3,",
        f"// {SOURCE},",
        f"// SHA-256 {SOURCE_SHA256}.",
        f"// Its COPYRIGHT property: {properties['COPYRIGHT']}",
        "#ifndef XSDK_TEXT_FONT_H",
        "#define XSDK_TEXT_FONT_H",
        "",
        "#include <stdint.h>",
        "",
        f"enum {{ TEXT_FONT_GLYPHS = {len(chosen)}, TEXT_FONT_ROWS = {CELL_HEIGHT} }};",
        "",
        "// Each glyph's code point, ascending; glyph 0, code point 0, is the font's default, a box.",
        "static const uint16_t text_font_code_points[TEXT_FONT_GLYPHS] = {",
    ]
    for i in range(0, len(chosen), 12):
        lines.append("\t" + ", ".join(f"0x{c:04X}" for c in chosen[i:i + 12]) + ",")
    lines += ["};", "", "// Each glyph's rows, top first, the leftmost pixel in bit 15.",
              "static const uint16_t text_font_rows[TEXT_FONT_GLYPHS][TEXT_FONT_ROWS] = {"]
    for c in chosen:
        rows = cell_rows(args.bdf, c, glyphs[c], ascent)
        half = CELL_HEIGHT // 2
        lines.append(f"\t// U+{c:04X}")
        lines.append("\t{ " + ", ".join(f"0x{r:04X}" for r in rows[:half]) + ",")
        lines.append("\t\t" + ", ".join(f"0x{r:04X}" for r in rows[half:]) + " },")
    lines += ["};", "", "#endif"]
    args.output.write_text("\n".join(lines) + "\n", newline="\n")
    print(f"{args.output}: {len(chosen)} glyphs, {len(chosen) * CELL_HEIGHT * 2} bytes of rows")


if __name__ == "__main__":
    main()
